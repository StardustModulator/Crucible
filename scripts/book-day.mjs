// Daily runner for the 7-day textbook plan.
//   node scripts/book-day.mjs                → progress across all days
//   node scripts/book-day.mjs 3              → day 3: pages, scenes to create/extend, status
//   node scripts/book-day.mjs 3 --ids        → just the scene ids for day 3 (for smoke.mjs)
//   node scripts/book-day.mjs --scene <id>   → full build spec of one scene (card + atoms by beat)
//   node scripts/book-day.mjs --page <book>  → atoms of one book page (use --pdf <n> for front matter)
//   node scripts/book-day.mjs --markdown     → write book/ROSTER.md (every day's scenes, beats, engine needs)
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { loadAtlas } from './book-check.mjs';

const read = (p) => JSON.parse(readFileSync(new URL(p, import.meta.url), 'utf8'));
const { days } = read('../book/days.json');
const { lines: LINES, offset: OFFSET } = read('../book/lines.json');
const files = loadAtlas();
const pages = new Map();
const scenes = new Map();
for (const { file, data } of files) {
  for (const s of data.scenes ?? []) scenes.set(s.id, { ...s, file, atoms: [] });
  for (const p of data.pages ?? []) pages.set(p.pdf, { ...p, file });
}
for (const p of pages.values()) for (const a of p.atoms) if (a.scene && scenes.has(a.scene)) scenes.get(a.scene).atoms.push({ ...a, pdf: p.pdf, book: p.book });
const built = (id) => existsSync(new URL(`../src/scenes/${id}.js`, import.meta.url));
const dayOf = (pdf) => days.find((d) => pdf >= d.pdf[0] && pdf <= d.pdf[1])?.day;
// A scene is "created" on the day of its first atom and "extended" on later days.
for (const s of scenes.values()) {
  const ds = [...new Set(s.atoms.map((a) => dayOf(a.pdf)))].sort((a, b) => a - b);
  s.createDay = ds[0] ?? dayOf((s.pages?.[0] ?? 1) + OFFSET);
  s.extendDays = ds.slice(1);
}

function dayInfo(d) {
  const ps = [];
  for (let p = d.pdf[0]; p <= d.pdf[1]; p++) ps.push(p);
  const inAtlas = ps.filter((p) => pages.has(p));
  const lines = ps.reduce((s, p) => s + LINES[p - 1], 0);
  const create = [...scenes.values()].filter((s) => s.createDay === d.day);
  const extend = [...scenes.values()].filter((s) => s.extendDays.includes(d.day));
  const need = [...create, ...extend];
  const done = need.filter((s) => built(s.id));
  return { ps, inAtlas, lines, create, extend, need, done };
}
const bar = (k, n, w = 20) => '█'.repeat(Math.round((w * k) / (n || 1))).padEnd(w, '░');

const args = process.argv.slice(2);
if (args[0] === '--markdown') {
  const out = ['# 📕 Scene roster', '', 'Generated by `node scripts/book-day.mjs --markdown` from the atlas — do not edit by hand.', ''];
  for (const d of days) {
    const i = dayInfo(d);
    const atomsToday = (s) => s.atoms.filter((a) => dayOf(a.pdf) === d.day);
    const engine = new Set(i.need.flatMap((s) => atomsToday(s).flatMap((a) => (a.engine ?? []).filter((e) => /^NEW/i.test(e)))));
    const n = i.ps.reduce((t, p) => t + (pages.get(p)?.atoms.length ?? 0), 0);
    out.push(`## ${d.icon} Day ${d.day} — ${d.theme}`, '', `${d.parts} · PDF ${d.pdf.join('–')} · book ${d.book} · ${i.ps.length} pages · ${i.lines} lines · ${n} atoms · ${i.create.length} new scenes · ${i.extend.length} extended`, '');
    out.push('| | scene | § | beats | atoms today |', '|---|---|---|---|---|');
    for (const s of i.create) out.push(`| 🆕 ${s.icon} | \`${s.id}\` ${s.title}${s.exists ? ` (builds on \`${s.exists}\`)` : ''} | ${s.section ?? ''} | ${s.beats.join(' · ')} | ${atomsToday(s).length} |`);
    for (const s of i.extend) out.push(`| ✚ ${s.icon} | \`${s.id}\` ${s.title} | ${s.section ?? ''} | ${s.beats.join(' · ')} | ${atomsToday(s).length} |`);
    if (engine.size) out.push('', '**Engine additions:** ' + [...engine].map((e) => '`' + e.replace(/^NEW:?\s*/i, '') + '`').join(', '));
    out.push('');
  }
  writeFileSync(new URL('../book/ROSTER.md', import.meta.url), out.join('\n'));
  console.log('wrote book/ROSTER.md');
} else if (args[0] === '--scene') {
  const s = scenes.get(args[1]);
  if (!s) { console.error(`no scene ${args[1]}`); process.exit(1); }
  console.log(`${s.icon} ${s.id} — ${s.title}   (${s.file}, §${s.section ?? '?'}, book pp ${s.pages?.join('–')})`);
  console.log(`uses: ${(s.uses ?? []).join(', ')}${s.exists ? `   exists: src/scenes/${s.exists}.js` : ''}   built: ${built(s.id) ? '🧱 yes' : 'no'}`);
  console.log(`brief: ${s.brief}\n`);
  for (const [i, beat] of s.beats.entries()) {
    console.log(`── beat ${i + 1}: ${beat}`);
    for (const a of s.atoms.filter((x) => x.beat === beat)) {
      console.log(`  • ${a.id} [${a.kind}${a.label ? ' ' + a.label : ''}] p${a.book ?? 'pdf' + a.pdf} L${a.lines.join('–')}  d${a.difficulty}`);
      console.log(`      idea:    ${a.idea}\n      feynman: ${a.feynman}\n      visual:  ${a.visual}${a.engine?.length ? `\n      engine:  ${a.engine.join(', ')}` : ''}`);
    }
  }
  const orphans = s.atoms.filter((a) => !s.beats.includes(a.beat));
  if (orphans.length) console.log(`\n⚠️ atoms whose beat is not in the card: ${orphans.map((a) => `${a.id}→"${a.beat}"`).join(', ')}`);
} else if (args[0] === '--page' || args[0] === '--pdf') {
  const pdf = args[0] === '--pdf' ? Number(args[1]) : Number(args[1]) + OFFSET;
  const p = pages.get(pdf);
  if (!p) { console.error(`pdf page ${pdf} is not in the atlas yet`); process.exit(1); }
  console.log(`📄 pdf ${pdf}${p.book ? ` · book ${p.book}` : ''} · §${p.section ?? '-'} · ${p.lines} lines · day ${dayOf(pdf)}\n${p.summary ?? ''}\n`);
  for (const a of p.atoms) console.log(`L${a.lines.join('–').padEnd(6)} ${a.kind.padEnd(11)} ${a.scene ? `${built(a.scene) ? '🧱' : '⬜'} ${a.scene} · ${a.beat}` : ''}\n        ${a.feynman ?? a.idea}`);
} else if (args[0] && /^\d+$/.test(args[0])) {
  const d = days.find((x) => x.day === Number(args[0]));
  const info = dayInfo(d);
  if (args.includes('--ids')) { console.log(info.need.map((s) => s.id).join(' ')); process.exit(0); }
  console.log(`${d.icon} Day ${d.day} — ${d.theme}\n   ${d.parts} · PDF ${d.pdf.join('–')} · book ${d.book} · ${info.ps.length} pages · ${info.lines} lines`);
  console.log(`   atlas: ${info.inAtlas.length}/${info.ps.length} pages   scenes: ${info.done.length}/${info.need.length} built\n`);
  for (const s of info.create) console.log(`   🆕 ${built(s.id) ? '🧱' : '⬜'} ${s.icon} ${s.id.padEnd(34)} ${s.beats.length} beats · ${s.atoms.filter((a) => dayOf(a.pdf) === d.day).length} atoms today`);
  for (const s of info.extend) console.log(`   ✚  ${built(s.id) ? '🧱' : '⬜'} ${s.icon} ${s.id.padEnd(34)} +${s.atoms.filter((a) => dayOf(a.pdf) === d.day).length} atoms today`);
  const missing = info.ps.filter((p) => !pages.has(p));
  if (missing.length) console.log(`\n   ⚠️ pages not yet in the atlas: ${missing.join(', ')}`);
} else {
  console.log('📕 The Book — 7-day plan\n');
  let tot = 0, totDone = 0;
  for (const d of days) {
    const i = dayInfo(d);
    tot += i.need.length; totDone += i.done.length;
    const ok = i.inAtlas.length === i.ps.length && i.need.length && i.done.length === i.need.length;
    console.log(`${ok ? '✅' : d.icon} Day ${d.day}  ${bar(i.done.length, i.need.length)} ${String(i.done.length).padStart(3)}/${String(i.need.length).padEnd(3)} scenes · atlas ${i.inAtlas.length}/${i.ps.length} pp · ${d.theme}`);
  }
  console.log(`\n   ${totDone}/${tot} scenes built · ${pages.size}/474 pages in atlas`);
}
